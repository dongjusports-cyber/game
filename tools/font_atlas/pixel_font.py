def _lookup(table: dict[str, list[str]], ch: str) -> list[str]:
    if ch in table:
        return table[ch]
    if ch.upper() in table:
        return table[ch.upper()]
    return table.get("?", ["###", "#.#", ".#.", "...", ".#."] if len(next(iter(table.values()))[0]) == 3 else _5X7["?"])


def glyph_size(ch: str, wide: bool) -> tuple[int, int]:
    rows = _lookup(_5X7 if wide else _3X5, ch)
    return len(rows[0]), len(rows)


def blit_glyph(img: Image.Image, ch: str, x: int, y: int, wide: bool = True) -> tuple[int, int]:
    """Vẽ 1 ký tự, trả (width, height). Cắt nếu ra ngoài ảnh."""
    rows = _lookup(_5X7 if wide else _3X5, ch)
    w, h = len(rows[0]), len(rows)
    px = img.load()
    iw, ih = img.size
    for dy, row in enumerate(rows):
        for dx, bit in enumerate(row):
            if bit != "#":
                continue
            xx, yy = x + dx, y + dy
            if 0 <= xx < iw and 0 <= yy < ih:
                px[xx, yy] = 255
    return w, h


def pick_wide(box_w: int, box_h: int) -> bool:
    """5×7 khi ô đủ chỗ; không thì 3×5."""
    return box_w >= 6 and box_h >= 8
